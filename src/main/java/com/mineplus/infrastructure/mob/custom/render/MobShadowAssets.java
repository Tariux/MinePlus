package com.mineplus.infrastructure.mob.custom.render;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import com.mineplus.infrastructure.virtual.rig.BoneRigAssetWriter;
import com.mineplus.pack.PackApi;
import java.nio.charset.StandardCharsets;

/**
 * The bundled ground-shadow plate: one flat, soft-edged quad a rigged mob
 * carries at its feet.
 *
 * <p>A rig replaces the base model on screen, and the base model is what draws
 * the vanilla shadow — without a replacement a custom mob looks like it is
 * floating. The plate is authored in anchored element space (the client
 * subtracts half a block, so the 0..16 quad lands centered on the display
 * origin) and scaled per mob from the mob's own width.</p>
 *
 * <p>Registration is idempotent and cheap: one generated model, one generated
 * items entry and one generated 32x32 texture, all produced in code.</p>
 */
public final class MobShadowAssets {

    public static final String NAMESPACE = "mineplus";
    public static final String COMPONENT_PATH = "mob/shadow";
    /** Plate width in blocks at scale 1: the 16px quad is exactly one block. */
    public static final float BASE_DIAMETER_BLOCKS = 1.0f;

    private static final Gson GSON = new GsonBuilder().disableHtmlEscaping().create();

    private MobShadowAssets() {
    }

    /** Registers the shadow plate (no-op when the pack subsystem is unavailable). */
    public static void register(PackApi pack) {
        if (pack == null || !pack.isAvailable()) {
            return;
        }
        pack.registerGeneratedAsset(NAMESPACE, "textures/" + COMPONENT_PATH + ".png",
                PngUtil.softShadowTexture(32));
        BoneRigAssetWriter.registerGenerated(pack, NAMESPACE, COMPONENT_PATH, plateJson());
    }

    private static byte[] plateJson() {
        JsonObject root = new JsonObject();
        root.addProperty("credit", "Generated by Mineplus");
        root.addProperty("ambientocclusion", false);
        JsonObject textures = new JsonObject();
        textures.addProperty("0", NAMESPACE + ":" + COMPONENT_PATH);
        textures.addProperty("particle", "minecraft:block/air");
        root.add("textures", textures);

        JsonArray elements = new JsonArray();
        JsonObject element = new JsonObject();
        // Anchored element space: 0..16 is one block centered on the display
        // origin, and the plate is a hair thick so both faces get a normal.
        element.add("from", vec3(0.0f, 7.94f, 0.0f));
        element.add("to", vec3(16.0f, 8.06f, 16.0f));
        element.addProperty("shade", false);
        element.addProperty("blend", true);
        JsonObject faces = new JsonObject();
        faces.add("up", face());
        faces.add("down", face());
        element.add("faces", faces);
        elements.add(element);
        root.add("elements", elements);
        return GSON.toJson(root).getBytes(StandardCharsets.UTF_8);
    }

    private static JsonObject face() {
        JsonArray uv = new JsonArray();
        uv.add(0.0f);
        uv.add(0.0f);
        uv.add(16.0f);
        uv.add(16.0f);
        JsonObject face = new JsonObject();
        face.add("uv", uv);
        face.addProperty("texture", "#0");
        return face;
    }

    private static JsonArray vec3(float x, float y, float z) {
        JsonArray array = new JsonArray();
        array.add(x);
        array.add(y);
        array.add(z);
        return array;
    }
}
