package com.mineplus.infrastructure.mob.custom.render;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import com.mineplus.infrastructure.virtual.rig.BoneRigAssetWriter;
import com.mineplus.pack.PackApi;
import java.nio.charset.StandardCharsets;

/**
 * The terminal fallback of the render chain: one neutral light-gray cube
 * (the bundled {@code mineplus:mob/fallback/cube} model) a mob of
 * {@code GENERIC_CUBE} fallback mode renders as when its own model cannot be
 * presented.
 *
 * <p>The cube references a <b>vanilla</b> texture, so it renders even when
 * this pack's own texture entries are broken — it is the asset that must never
 * be purple/black, and depending on our own broken state to color itself would
 * be circular. Registration is idempotent.</p>
 */
public final class GenericFallbackAssets {

    public static final String NAMESPACE = "mineplus";
    public static final String COMPONENT_PATH = "mob/fallback/cube";

    private static final Gson GSON = new GsonBuilder().disableHtmlEscaping().create();

    private GenericFallbackAssets() {
    }

    /** Registers the fallback cube (no-op when the pack subsystem is unavailable). */
    public static void register(PackApi pack) {
        if (pack == null || !pack.isAvailable()) {
            return;
        }
        BoneRigAssetWriter.registerGenerated(pack, NAMESPACE, COMPONENT_PATH, cubeJson());
    }

    private static byte[] cubeJson() {
        JsonObject root = new JsonObject();
        root.addProperty("credit", "Generated by Mineplus");
        root.addProperty("ambientocclusion", false);
        JsonObject textures = new JsonObject();
        textures.addProperty("0", "minecraft:block/light_gray_concrete");
        textures.addProperty("particle", "minecraft:block/light_gray_concrete");
        root.add("textures", textures);

        JsonArray elements = new JsonArray();
        JsonObject element = new JsonObject();
        // Anchored element space: the client subtracts half a block, so the
        // 0..16 cube renders centered on the display origin.
        element.add("from", vec3(0, 0, 0));
        element.add("to", vec3(16, 16, 16));
        element.addProperty("shade", false);
        JsonObject faces = new JsonObject();
        for (String direction : new String[]{"north", "south", "east", "west", "up", "down"}) {
            faces.add(direction, face());
        }
        element.add("faces", faces);
        elements.add(element);
        root.add("elements", elements);
        return GSON.toJson(root).getBytes(StandardCharsets.UTF_8);
    }

    private static JsonObject face() {
        JsonArray uv = new JsonArray();
        uv.add(0.0f);
        uv.add(0.0f);
        uv.add(16.0f);
        uv.add(16.0f);
        JsonObject face = new JsonObject();
        face.add("uv", uv);
        face.addProperty("texture", "#0");
        return face;
    }

    private static JsonArray vec3(float x, float y, float z) {
        JsonArray array = new JsonArray();
        array.add(x);
        array.add(y);
        array.add(z);
        return array;
    }
}
